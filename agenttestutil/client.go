// Client configures the client of the agent bound to addr: the key generated by client is written to a new user
// configuration directory, and the configuration for Environment is written to a new workspace. the process
// is pointed at both, the client commands look for them in the XDG_CONFIG_HOME and the current directory.
// client must be the key generator given to Agent, and Client doesn't wait for the agent to be ready, see WaitQuorum.
// the options are applied last so tests can override anything.
func Client(t *testing.T, id rsax.KeyGen, addr *net.TCPAddr, options ...agent.ConfigClientOption) error {
	t.Helper()

	var (
		xdg       = t.TempDir()
		workspace = t.TempDir()
		envdir    = filepath.Join(workspace, bw.DefaultDeployspaceConfigDir, Environment)
	)

	if err := fsx.MkDirs(0700, filepath.Join(xdg, "bearded-wookie"), envdir); err != nil { // must exist or the user's home is used.
		return err
	}

	t.Setenv("XDG_CONFIG_HOME", xdg)

	if _, err := notary.NewDeterministicSigner(id, "test"); err != nil {
		return err
	}

	// CCOptionAddress isn't used, it forces the default port.
	config := agent.NewConfigClient(
		agent.ExampleConfigClient(agent.CCOptionTLSConfig(Environment), agent.CCOptionConcurrency(1)),
		append([]agent.ConfigClientOption{
			func(c *agent.ConfigClient) {
				c.Address = addr.String()
				c.ServerName = "localhost"
				c.Credentials.Mode = "disabled"
				c.Deployment.Prompt = ""
			},
		}, options...)...,
	)

	if err := WriteClient(filepath.Join(envdir, bw.DefaultClientConfig), config); err != nil {
		return err
	}

	t.Chdir(workspace)

	return nil
}

// connect to the cluster as the client configured by Client.
func connect(ctx context.Context) (dialers.Defaults, clustering.Rendezvous, error) {
	config, err := commandutils.LoadConfiguration(ctx, Environment, agent.CCOptionInsecure(true))
	if err != nil {
		return nil, nil, err
	}

	ss, err := notary.NewAutoSigner(vcsinfo.CurrentUserDisplay(config.WorkDir()))
	if err != nil {
		return nil, nil, err
	}

	return daemons.ConnectClientUntilSuccess(ctx, config, ss, grpc.WithPerRPCCredentials(ss))
}

// QuorumInfo retrieves the information of the quorum, as the client configured by Client.
func QuorumInfo(ctx context.Context) (*agent.InfoResponse, error) {
	d, c, err := connect(ctx)
	if err != nil {
		return nil, err
	}

	return quorumInfo(ctx, dialers.NewQuorum(c, d.Defaults()...))
}

func quorumInfo(ctx context.Context, qd dialers.Quorum) (*agent.InfoResponse, error) {
	conn, err := qd.DialContext(ctx)
	if err != nil {
		return nil, err
	}
	defer conn.Close()

	return agent.NewConn(conn).QuorumInfo(ctx)
}

// WaitQuorum blocks until the agent has joined the quorum and has a leader.
// the agent accepts connections before then, but rejects the operations that require the quorum.
func WaitQuorum(parent context.Context) error {
	return WaitNodes(parent, 1)
}

// WaitNodes blocks until the quorum has a leader and the client sees at least n nodes in the cluster.
// the deploy goes to the nodes the client sees, so a cluster is only ready once all of them are visible.
func WaitNodes(parent context.Context, n int) error {
	ctx, done := context.WithTimeout(parent, 30*time.Second)
	defer done()

	d, c, err := connect(ctx)
	if err != nil {
		return err
	}

	qd := dialers.NewQuorum(c, d.Defaults()...)

	for {
		if info, err := quorumInfo(ctx, qd); err == nil && info.Leader != nil && len(c.Members()) >= n {
			return nil
		}

		select {
		case <-ctx.Done():
			return fmt.Errorf("cluster did not become ready, want %d nodes: %w", n, ctx.Err())
		case <-time.After(100 * time.Millisecond):
		}
	}
}
